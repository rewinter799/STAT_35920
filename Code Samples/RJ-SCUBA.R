subnumber=function(x,cl,cg,G){##find the subgroup label for all data x using current cl, cg and G
	subn=rep(0,nrow(x))
	for(j in 1:length(cl)){
		if(G[j]==2) subn=subn+mul(j-1,G+1)*findInterval(x[,j],c(cl[j],cl[j]+cg[j]))
		else subn=subn+mul(j-1,G+1)*findInterval(x[,j],cl[j])
	}
	subn+1
}

########################################################


########################################################
mul=function(i,y){## function that does product of numbers; but takes value 1 when length(y)=0
	if(i==0)ttt=1
	else ttt=prod(y[1:i])
	
	ttt
}
########################################################



########################################################
ratio=function(y,theta,tloc,subn,subnstar,cl,clstar,cg,cgstar,mu1,sigma1,mu2,sigma2,j,lorg){
	##acceptance ratio in metroplis step for cg and cl
	if(lorg=="l"){
		ratio=exp(-sum(y*log(theta[tloc][subn])+(1-y)*log(1-theta[tloc][subn]))+sum(y*log(theta[tloc][subnstar])+(1-y)*log(1-theta[tloc][subnstar]))-((clstar[j]-mu1)^2-(cl[j]-mu1)^2)/(2*sigma1^2))
	}
	if(lorg=="g"){
		ratio=exp(-sum(y*log(theta[tloc][subn])+(1-y)*log(1-theta[tloc][subn]))+sum(y*log(theta[tloc][subnstar])+(1-y)*log(1-theta[tloc][subnstar]))-((log(cgstar[j])-mu2)^2-(log(cg[j])-mu2)^2)/(2*sigma2^2))
			}
	ratio
}

########################################################



########################################################
thetaloc=function(index,nx,G){##locate theta
    index[1]+sum(sapply(2:nx-1,mul,y=G+1)*(index[2:nx]-1))
}

########################################################	
	

########################################################
Gupdate=function(y,subn,theta,tloc,index,cl,cg,G,prior,Gprop,nx){#only delta
	#propose a new G using RJ
    for (j in 1:nx){
		if(runif(1,0,1)<0.5){
			Gnew=G
			Gnew[j]=3-G[j]
			if(G[j]==1){
				clnew=cl
				cgnew=cg
				u=rgamma(1,Gprop$ga,Gprop$gb)
				cgnew[j]=u
				v=rbeta(prod(G[-j]+1),Gprop$ba,Gprop$bb)
				index1=index[order(index[,j]),]
				indexadd=index1[1:(0.5*nrow(index)),]
				index1[which(index1[,j]==2),j]=3
				indexadd[,j]=2
				indexnew=rbind(index1,indexadd)
				tlocnew=apply(indexnew,1,thetaloc,nx,Gnew)
				thetanew=c(theta,v)
				
				subnnew=subnumber(x,clnew,cgnew,Gnew)
				
				Gratio = exp(
                                    sum(y*log(thetanew[order(tlocnew)][subnnew]) +(1-y)*log(1-thetanew[order(tlocnew)][subnnew]))   -sum(y*log(theta[order(tloc)][subn])+(1-y)*log(1-theta[order(tloc)][subn])))                                * prod(dbeta(v,prior$a,prior$b)) * exp(-((clnew[j]-prior$mu1)^2-(cl[j]-prior$mu1)^2)/2/prior$sigma1^2)                                * dlnorm(u,prior$mu2,prior$sigma2)   *p2/p1*ps/(1-ps)               /dgamma(u,Gprop$ga,Gprop$gb)/prod(dbeta(v,Gprop$ba,Gprop$bb))			
				
			}
			
			if(G[j]==2){
				clnew=cl
				cgnew=cg
				u=cg[j]
				index1=index[which(index[,j]!=2),]
				thetanew=theta[which(index[,j]!=2)]
				v=theta[which(index[,j]==2)]
				indexnew=index1
				indexnew[which(index1[,j]==3),j]=2
				tlocnew=apply(indexnew,1,thetaloc,nx,Gnew)
				subnnew=subnumber(x,clnew,cgnew,Gnew)
				
				Gratio=exp(sum(y*log(thetanew[order(tlocnew)][subnnew])+(1-y)*log(1-thetanew[order(tlocnew)][subnnew]))-sum(y*log(theta[order(tloc)][subn])+(1-y)*log(1-theta[order(tloc)][subn])))/prod(dbeta(v,prior$a,prior$b))*exp(-((clnew[j]-prior$mu1)^2-(cl[j]-prior$mu1)^2)/2/prior$sigma1^2)/dlnorm(u,prior$mu2,prior$sigma2)*p1/p2*pm/(1-pm)*dgamma(u,Gprop$ga,Gprop$gb)*prod(dbeta(v,Gprop$ba,Gprop$bb))
				
			}
			
			if (runif(1,0,1)<Gratio){
					cl=clnew
					cg=cgnew
					index=indexnew
					tloc=tlocnew
					theta=thetanew
					subn=subnnew
					G=Gnew
				}
			}
	}
	return(list(cl=cl,cg=cg,index=index,tloc=tloc,theta=theta,subn=subn,G=G))
}

