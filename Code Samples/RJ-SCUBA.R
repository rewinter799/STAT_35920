############### Reversible jump example for a subgroup identification problem #######################
#########       Wentian Guo, Yuan Ji May 2017                                 #######################

### Index: i=1,..., I subgroups;     j=1,...n patients;     s=1,..., S=2 biomarkers

## Assume j=1,... n patients have nx=2 biomarker measurements.
## Assume each biomarker s can be divided by up to G_s=2 values. Where there is one cutoff value, we use c_s | G_s=1 ~ N(mu_1, sigma^2_1) to denote the cutoff. When there are two cutoff values. The smaller one C_sl | G_s = 2 ~ N(mu_1, sigma^2_1) and the larger one is c_sl + c_sg, where c_sg ~ log-Normal(mu_2, sigma^2_2). Given G_1 and G_2, and C's (the cutoff values), we have a partition of the two-dimensional biomarker space. Let I denote the number of subgroups generated by the cutoff values. For a patient, given his/her two biomarker values, he/she will be assigned to a subgroup, denoted by l_j = i, j=1,..., n, and i=1,..., I.

## Assume y_j is thebinary outcome for patient j (such as reponse to a drug). Then assume y_j | {l_j = i, G, C} ~ Bern(theta_i). Let theta_i ~ Beta(a, b)
## Also, Priors: Pr(G_s = 1) = p1, Pr(G_s = 2) = 1-p1


